#!/usr/bin/env python3
"""Generate the Grafana ConfigMap, or check that it matches its source JSON."""

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "dashboards/rosa-boundary.json"
TARGET = ROOT / "dashboards/manifests/grafana-dashboard-rosa-boundary.configmap.yaml"
HEADER = """# Generated by scripts/generate_dashboard_manifest.py; do not edit.
apiVersion: v1
kind: ConfigMap
metadata:
  name: grafana-dashboard-rosa-boundary
  labels:
    grafana_dashboard: "true"
  annotations:
    grafana-folder: /grafana-dashboard-definitions/ROSA Boundary
data:
  rosa-boundary.json: |-
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="exit with status 1 if the manifest is missing or out of date; write nothing",
    )
    args = parser.parse_args()

    try:
        source = SOURCE.read_text(encoding="utf-8")
        json.loads(source)
        manifest = HEADER + "".join(
            ("    " + line if line else "") + "\n" for line in source.splitlines()
        )
        if args.check:
            if not TARGET.exists() or TARGET.read_bytes() != manifest.encode("utf-8"):
                print(
                    "Dashboard manifest is missing or out of date. Run: "
                    "python3 scripts/generate_dashboard_manifest.py",
                    file=sys.stderr,
                )
                return 1
            print("Dashboard manifest is up to date.")
        else:
            TARGET.parent.mkdir(parents=True, exist_ok=True)
            TARGET.write_text(manifest, encoding="utf-8")
            print(f"Generated {TARGET.relative_to(ROOT)}")
    except (OSError, json.JSONDecodeError) as error:
        print(f"Cannot generate dashboard manifest: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
